#include "SuiteSettings.h"

namespace
{
    // Plan 05 R4: the default window stays inside the suite budget (1000x700). The knob
    // size comes from the SuiteUI tokens (R1); never set slider bounds that exceed them.
    constexpr int editorWidth = 980;
    constexpr int editorHeight = 700;
    constexpr int headerHeight = 44;
    constexpr int footerHeight = 26;
    constexpr int groupGap = 8;   // the suite's one-gap rule (plan 05 R7)
    constexpr int groupTitleHeight = SuiteUI::groupTitleHeight;
    constexpr int groupInnerHeight = 2 * SuiteUI::knobRowHeight + groupGap;
    constexpr int groupHeight = groupTitleHeight + 4 + groupInnerHeight + 4;
    constexpr int visualHeight = 130;

    const juce::Image& brandLockup()
    {
        static const juce::Image image = juce::ImageCache::getFromMemory (BinaryData::lockup_multiband_saturation_png,
                                                                          BinaryData::lockup_multiband_saturation_pngSize);
        return image;
    }
}

MultibandSaturationEditor::MultibandSaturationEditor (MultibandSaturationProcessor& p)
    : AudioProcessorEditor (&p),
      processor (p)
{
    setLookAndFeel (&lookAndFeel);

    // The bar exists before setSize(), because setSize() runs resized(), which lays the bar out.
    presetBar.reset (new SuitePresets::PresetBar (static_cast<SuitePresets::StateHolder&> (processor),
                                                  juce::Colour (0xffFF6B6B)));

    setSize (editorWidth, editorHeight);
    setResizable (true, true);
    setResizeLimits (editorWidth - 60, editorHeight - 60, 1200, 1200);

    // Rule #3 (plan 11): three options, so a pill.
    modeCell.setOptions ({ "Tube", "Tape", "Diode" });
    modeCell.attachToParameter (processor.apvts.getParameter (MultibandSaturationProcessor::modeId));

    crossoverCtrl.setHelpText ("The Linkwitz-Riley split point between the two bands.");
    driveLowCtrl.setHelpText ("Pre-gain of the low band's shaper.");
    driveHighCtrl.setHelpText ("Pre-gain of the high band's shaper.");
    toneLowCtrl.setHelpText ("Tilt around 1 kHz on the shaped low band.");
    toneHighCtrl.setHelpText ("Tilt around 1 kHz on the shaped high band.");
    sensitivityCtrl.setHelpText ("How far the envelopes push the drives.");
    attackCtrl.setHelpText ("Envelope rise, both bands.");
    releaseCtrl.setHelpText ("Envelope fall, both bands.");
    mixCtrl.setHelpText ("Dry/wet balance.");
    outputCtrl.setHelpText ("Output level after the mix.");
    modeCell.setHelpText ("The saturation curve, shared by both bands.");

    addAndMakeVisible (crossoverCtrl);
    addAndMakeVisible (driveLowCtrl);
    addAndMakeVisible (driveHighCtrl);
    addAndMakeVisible (toneLowCtrl);
    addAndMakeVisible (toneHighCtrl);
    addAndMakeVisible (sensitivityCtrl);
    addAndMakeVisible (attackCtrl);
    addAndMakeVisible (releaseCtrl);
    addAndMakeVisible (mixCtrl);
    addAndMakeVisible (outputCtrl);
    addAndMakeVisible (modeCell);
    addAndMakeVisible (visualizer);

    addAndMakeVisible (gearButton);

    // Gear menu (R13): About… and Settings…, the same two actions every suite plugin has.
    gearButton.onAbout = [this]
    {
        SuiteUI::showAboutDialog (brandLockup(), SUITE_PLUGIN_NAME, SUITE_PLUGIN_VERSION,
                                  SUITE_PLUGIN_CODE, SUITE_PLUGIN_ID, this);
    };
    gearButton.onSettings = [this]
    {
        SuiteSettings::showSettingsDialog (SuiteSettings::shared(), this);
    };

    if (presetBar->getPreferredHeight() > 0)
        addAndMakeVisible (*presetBar);
    presetBar->onPresetLoaded = [this] { repaint(); };

    startTimerHz (SuiteUI::kRefreshHz);
}

MultibandSaturationEditor::~MultibandSaturationEditor()
{
    stopTimer();
    setLookAndFeel (nullptr);
}

void MultibandSaturationEditor::paint (juce::Graphics& g)
{
    juce::ColourGradient background (SuiteUI::Colours::panelLight, 0.0f, 0.0f,
                                     SuiteUI::Colours::background, 0.0f, (float) getHeight(), false);
    g.setGradientFill (background);
    g.fillAll();

    // Brand lockup at the left of the header (the FROTH Audio wordmark, the mark and
    // the product name, generated by tools/brand/lockups.py and embedded in the bundle).
    SuiteUI::drawBrandLockup (g, getLocalBounds().removeFromTop (headerHeight).reduced (16, 0), brandLockup());

    // The two group frames and their titles (R5: 15 pt bold in the accent).
    g.setColour (lookAndFeel.getAccent());
    g.setFont (juce::Font (juce::FontOptions (15.0f, juce::Font::bold)));
    g.drawText ("SPLIT", splitGroupBounds.withHeight (groupTitleHeight).translated (0, 4).reduced (12, 0),
                juce::Justification::centredLeft);
    g.drawText ("SHAPER", shaperGroupBounds.withHeight (groupTitleHeight).translated (0, 4).reduced (12, 0),
                juce::Justification::centredLeft);

    g.setColour (SuiteUI::Colours::textDim);
    g.setFont (SuiteUI::uiFont (11.0f));
    g.drawText ("Two bands, each with its own drive and tone. The bands sum back to the input's level.",
                getLocalBounds().removeFromBottom (footerHeight).reduced (16, 0),
                juce::Justification::centredLeft);
}

void MultibandSaturationEditor::resized()
{
    auto area = getLocalBounds().reduced (16);

    // Header: gear at the far right, the preset bar flat to its left (plan 05.1).
    auto headerArea = area.removeFromTop (headerHeight);
    gearButton.setBounds (headerArea.removeFromRight (26).withHeight (26)
                            .withY (headerArea.getCentreY() - 13));
    const int barHeight = presetBar != nullptr ? presetBar->getPreferredHeight() : 0;
    if (barHeight > 0)
        presetBar->setBounds (headerArea.removeFromRight (300).withHeight (barHeight)
                                .withY (headerArea.getCentreY() - barHeight / 2));

    area.removeFromTop (groupGap);

    // The dual-band visual spans the window between the header and the groups (plan 11 4b).
    visualBounds = area.removeFromTop (visualHeight);
    visualizer.setBounds (visualBounds);

    area.removeFromTop (groupGap);

    splitGroupBounds = area.removeFromTop (groupHeight);
    area.removeFromTop (groupGap);
    shaperGroupBounds = area.removeFromTop (groupHeight);

    // SPLIT: the crossover and the shared saturation mode.
    {
        auto inner = splitGroupBounds.withTrimmedTop (groupTitleHeight + 4).reduced (10, 4);
        const int cellWidth = inner.getWidth() / 4;
        auto row = inner.removeFromTop (SuiteUI::knobRowHeight);
        crossoverCtrl.setBounds (row.removeFromLeft (cellWidth).reduced (3));
        modeCell.setBounds (row.removeFromLeft (cellWidth).reduced (3));
    }

    // SHAPER: per-band drive and tone / envelope, mix, output.
    {
        auto inner = shaperGroupBounds.withTrimmedTop (groupTitleHeight + 4).reduced (10, 4);

        auto row1 = inner.removeFromTop (SuiteUI::knobRowHeight);
        const int cellWidth1 = row1.getWidth() / 4;
        for (auto* knob : { &driveLowCtrl, &driveHighCtrl, &toneLowCtrl, &toneHighCtrl })
            knob->setBounds (row1.removeFromLeft (cellWidth1));

        auto row2 = inner.removeFromBottom (SuiteUI::knobRowHeight);
        const int cellWidth2 = row2.getWidth() / 5;
        for (auto* knob : { &sensitivityCtrl, &attackCtrl, &releaseCtrl, &mixCtrl, &outputCtrl })
            knob->setBounds (row2.removeFromLeft (cellWidth2));
    }
}

